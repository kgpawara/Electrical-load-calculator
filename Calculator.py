import math

class ElectricalCalculator:
    def single_phase_power(self, voltage, current, pf=0.8):
            power_w = voltage * current * pf
            return power_w, power_w / 1000

    def three_phase_power(self, line_voltage, line_current, pf=0.8):
            power_w = math.sqrt(3) * line_voltage * line_current * pf
            return power_w, power_w / 1000

    def amps_from_kw(self, kw, voltage, pf=0.8, phase=1):
            watts = kw * 1000
            if phase == 1:
                current = watts / (voltage * pf)
            else:
                current = watts / (math.sqrt(3) * voltage * pf)
            return round(current, 2)

